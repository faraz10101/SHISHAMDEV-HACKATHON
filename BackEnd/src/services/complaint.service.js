// Builds a ready-to-copy complaint summary once enough independent people reported the same target.
const Report = require('../models/Report.model');
const ai = require('./ai/aiRouter');
const { COMPLAINT_SYSTEM } = require('./ai/prompts');
const { SCAM_LABELS, LEVELS } = require('../config/constants');

const fmt = (d) => new Date(d).toISOString().slice(0, 10);

async function buildComplaintPack(kind, value) {
  const field = kind === 'number' ? 'numbers' : 'hosts';
  const reports = await Report.find({ [field]: value }).sort({ createdAt: 1 })
    .select('scamType brand snippet city createdAt reporterHash amountLost');

  const uniqueReporters = new Set(reports.map((r) => r.reporterHash)).size;
  if (uniqueReporters < LEVELS.CRITICAL_MIN) {
    const err = new Error(`A complaint summary needs at least ${LEVELS.CRITICAL_MIN} independent reports. This one has ${uniqueReporters}.`);
    err.status = 403;
    throw err;
  }

  const types = {};
  let loss = 0;
  for (const r of reports) { types[r.scamType] = (types[r.scamType] || 0) + 1; loss += r.amountLost || 0; }
  const typeLabels = Object.keys(types).map((t) => SCAM_LABELS[t] || t);
  const first = reports[0].createdAt;
  const last = reports[reports.length - 1].createdAt;
  const samples = [...new Set(reports.map((r) => r.snippet).filter(Boolean))].slice(0, 5);
  const cities = [...new Set(reports.map((r) => r.city).filter(Boolean))].slice(0, 5);

  const facts = { target: `${kind}: ${value}`, independentReports: uniqueReporters, firstReported: fmt(first), lastReported: fmt(last), scamTypes: typeLabels, selfReportedLossRs: loss, cities };
  let summary = `${uniqueReporters} different people reported the ${kind} ${value} between ${fmt(first)} and ${fmt(last)}. Reported scam type: ${typeLabels.join(', ')}. These are community reports and have not been verified.`;
  try {
    const r = await ai.generateJSON({ system: COMPLAINT_SYSTEM, prompt: JSON.stringify(facts), validate: (o) => o && typeof o.summary === 'string' });
    summary = r.data.summary;
  } catch { /* keep template */ }

  const text = [
    'COMPLAINT SUMMARY (generated by ScamShield)',
    '',
    `Reported ${kind}: ${value}`,
    `Independent reports: ${uniqueReporters} (${fmt(first)} to ${fmt(last)})`,
    `Scam type(s): ${typeLabels.join(', ')}`,
    cities.length ? `Cities mentioned: ${cities.join(', ')}` : null,
    `Losses reported by users (unverified): Rs ${loss.toLocaleString('en-US')}`,
    '',
    'Summary:',
    summary,
    '',
    'Sample messages (personal details removed):',
    ...samples.map((s, i) => `${i + 1}. ${s}`),
    '',
    'Note: This summary was compiled from community reports submitted to ScamShield and has not been independently verified. Please submit it through the official complaint channel of the relevant authority, and confirm that channel on the authority\'s official website.',
  ].filter((l) => l !== null).join('\n');

  return { target: { kind, value }, uniqueReporters, firstReportedAt: first, lastReportedAt: last, scamTypes: typeLabels, reportedLoss: loss, summary, samples, text };
}

module.exports = { buildComplaintPack };
